// Deterministic, static CommonJS bundling. No eval, runtime imports or packages.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
function bundle() {
  const modules = [];
  const ids = new Map();
  function add(file) {
    if (ids.has(file)) return ids.get(file);
    const id = modules.length;
    ids.set(file,id); modules.push('');
    const extension = path.extname(file);
    let code;
    if (extension === '.css' || extension === '.json') {
      const raw = fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');
      code = 'module.exports = '+JSON.stringify(extension === '.json' ? JSON.parse(raw) : raw)+';';
    } else {
      code = fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n').replace(/require\(['"]([^'"]+)['"]\)/g,(_,request)=> {
        if (!request.startsWith('.')) throw new Error('Only local modules are supported');
        let dependency = path.resolve(path.dirname(file),request);
        if (!path.extname(dependency)) dependency += '.js';
        return `require(${add(dependency)})`;
      });
    }
    modules[id] = `function(module,exports,require){\n${code}\n}`;
    return id;
  }
  const entry = add(path.join(root,'src/app.js'));
  return `// Generated by node scripts/build.cjs. Edit src/ and _locales/, not this file.\n(()=>{\n'use strict';\nconst modules=[${modules.join(',\n')}];\nconst cache={};\nfunction require(id){if(cache[id])return cache[id].exports;const module=cache[id]={exports:{}};modules[id](module,module.exports,require);return module.exports;}\nrequire(${entry});\n})();\n`;
}
if (require.main === module) {
  const output = bundle(), target = path.join(root,'content.js');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target,'utf8') !== output) { console.error('content.js is stale; run npm run build'); process.exitCode=1; }
  } else fs.writeFileSync(target,output);
}
module.exports = bundle;
